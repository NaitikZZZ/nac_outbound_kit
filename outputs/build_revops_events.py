def main():
    rows = []
    for ev in EVENTS:
        for name, title, company in ev["speakers"]:
            rows.append({
                "Event": ev["event"],
                "Date": ev["date"],
                "Location": ev["location"],
                "Speaker": name,
                "Job Title": title,
                "Company": company,
                "Event URL": ev["url"],
            })

    csv_path = "outputs/revenueops-events-speakers.csv"
    with open(csv_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=[
            "Event", "Date", "Location", "Speaker", "Job Title", "Company", "Event URL"])
        writer.writeheader()
        writer.writerows(rows)

    print(f"Events: {len(EVENTS)}")
    print(f"Total speaker rows: {len(rows)}")
    print(f"Unique speakers: {len(set(r['Speaker'] for r in rows))}")
    print(f"Wrote {csv_path}")


if __name__ == "__main__":
    main()
